// Copies the repository README's sections into the website, so /docs never drifts from it.
// Runs before dev, build, lint, typecheck and tests. Output is generated and gitignored.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const readme = readFileSync(join(here, '..', '..', 'README.md'), 'utf8');

const sections = [];
let current = null;
for (const line of readme.split(/\r?\n/)) {
  const h2 = /^## (.+)$/.exec(line);
  if (h2) {
    current = { title: h2[1].trim(), lines: [] };
    sections.push(current);
  } else if (current) {
    current.lines.push(line);
  }
}

const slug = (t) =>
  t
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const out = sections.map((s) => ({
  id: slug(s.title),
  title: s.title,
  markdown: s.lines.join('\n').trim(),
}));

const target = join(here, '..', 'src', 'content', 'readme.generated.ts');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/sync-docs.mjs from ../README.md. Do not edit.\n` +
    `export const README_SECTIONS: readonly { id: string; title: string; markdown: string }[] = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`docs: ${out.length} README sections synced`);
